import test from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { mkdtempSync, mkdirSync, writeFileSync, copyFileSync, unlinkSync, readdirSync, rmdirSync, existsSync, constants } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const child = fileURLToPath(new URL('./recovery-process.fixture.mjs', import.meta.url));
const run = (folder, mode, wrappingKey, otherOwner = false) => {
  const result = spawnSync(process.execPath, [child], { windowsHide: true, shell: false, timeout: 10_000,
    input: JSON.stringify({ syntheticOnly: true, folder, mode, wrappingKey: wrappingKey?.toString('base64url'), otherOwner }),
    encoding: 'utf8', maxBuffer: 64 * 1024 });
  assert.equal(result.error, undefined, 'synthetic child must finish within 10 seconds');
  const output = JSON.parse(result.stdout);
  assert.equal(result.status, output.ok ? 0 : 1);
  return output;
};

test('fresh OS processes restore copied ciphertext + wrapped keys, with no live files or previous data-key memory', (t) => {
  const root = mkdtempSync(join(tmpdir(), 'neko-key-recovery-'));
  const primary = join(root, 'synthetic-primary');
  const recovered = join(root, 'synthetic-restored');
  for (const folder of [primary, recovered]) {
    mkdirSync(folder);
    writeFileSync(join(folder, 'SYNTHETIC_ONLY'), 'neko-offline-test', { flag: 'wx' });
  }
  t.after(() => {
    // These exact two generated directories only; no recursive home/workspace deletion.
    for (const folder of [primary, recovered]) {
      for (const name of readdirSync(folder)) unlinkSync(join(folder, name));
      rmdirSync(folder);
    }
    rmdirSync(root);
  });
  const rootKey = randomBytes(32); // Synthetic stand-in for separately available KMS wrapping key.
  const seeded = run(primary, 'seed', rootKey);
  assert.equal(seeded.ok, true);
  for (const name of ['archive.sqlite', 'keys.jwe']) {
    copyFileSync(join(primary, name), join(recovered, name), constants.COPYFILE_EXCL);
    unlinkSync(join(primary, name)); // Only synthetic files generated by this test.
    assert.equal(existsSync(join(primary, name)), false);
  }
  const restored = run(recovered, 'restore', rootKey);
  assert.equal(restored.ok, true);
  assert.notEqual(restored.pid, seeded.pid);
  assert.deepEqual(restored.records, seeded.records);
  assert.equal(restored.records.length, 1);
  assert.deepEqual(run(recovered, 'restore', undefined), { ok: false, code: 'WRAPPING_KEY_UNAVAILABLE' });
  assert.deepEqual(run(recovered, 'restore', randomBytes(32)), { ok: false, code: 'KEY_BUNDLE_UNREADABLE' });
  assert.deepEqual(run(recovered, 'restore', rootKey, true), { ok: false, code: 'RECORD_NOT_FOUND' });
});
